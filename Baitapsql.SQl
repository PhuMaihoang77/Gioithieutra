CREATE or alter  FUNCTION F_SX (
    @MSCN VARCHAR(10),
    @Month INT,
    @Year INT
)
RETURNS TABLE
AS
RETURN 
(
    SELECT 
        Sa.MASP,
        Sa.TENSP,
        SUM(S.SOLUONG * Sa.DONGIA) AS Tsoluong,
        C.DINHMUC2
    FROM 
        SANXUAT S 
        JOIN SANPHAM Sa ON S.MASP = Sa.MASP 
        JOIN CN_SP C ON C.MASP = Sa.MASP 
    WHERE 
        MONTH(S.NGAYSX) = @Month 
        AND YEAR(S.NGAYSX) = @Year 
        AND S.MACN = @MSCN
    GROUP BY 
        Sa.MASP,
        Sa.TENSP,
        C.DINHMUC2
    HAVING 
        SUM(S.SOLUONG * Sa.DONGIA) >= C.DINHMUC2
);


