CREATE OR ALTER PROCEDURE P_TC(
    @n INT,           
    @m INT,           
    @Mapx VARCHAR(10) 
)
AS
BEGIN
    WITH TotalQuantity AS (
        SELECT   p.MAPX, x.TENPX,  SUM(sx.SOLUONG) AS TongSoLuong,   s.DONGIA
        FROM 
            PX_SP p
            JOIN SANPHAM s ON p.MASP = s.MASP
            JOIN PHANXUONG x ON x.MAPX = p.MAPX
            JOIN SANXUAT sx ON sx.MASP = p.MASP
        WHERE 
            MONTH(sx.NGAYSX) = @n 
            AND YEAR(sx.NGAYSX) = @m 
            AND x.MAPX = @Mapx
        GROUP BY 
            p.MAPX, x.TENPX, s.DONGIA
    )
    SELECT 
        MAPX, 
        TENPX, 
        SUM(TongSoLuong * DONGIA) AS TongTienCong
    FROM 
        TotalQuantity
    GROUP BY 
        MAPX, TENPX;
END;
go

