CREATE TABLE SANPHAM (
    MASP VARCHAR(10) NOT NULL,
    TENSP NVARCHAR(100) NOT NULL,
    DVT NVARCHAR(20),
    DONGIA INT CHECK (DONGIA >= 0),
    PRIMARY KEY (MASP)
);
GO
CREATE TABLE PHANXUONG (
    MAPX VARCHAR(10) NOT NULL,
    TENPX NVARCHAR(50),
    PRIMARY KEY (MAPX)
);
GO
CREATE TABLE PX_SP (
    MAPX VARCHAR(10) NOT NULL,
    MASP VARCHAR(10) NOT NULL,
    DINHMUC1 INT CHECK (DINHMUC1 >= 0),
    PRIMARY KEY (MAPX, MASP),
    FOREIGN KEY (MAPX) REFERENCES PHANXUONG(MAPX),
    FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP)
);
GO
CREATE TABLE CN_SP (
    MACN VARCHAR(15) NOT NULL,
    MASP VARCHAR(10) NOT NULL,
    DINHMUC2 INT CHECK (DINHMUC2 >= 0),
    PRIMARY KEY (MACN, MASP),
    FOREIGN KEY (MACN) REFERENCES CONGNHAN(MACN),
    FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP)
);
GO
CREATE TABLE CONGNHAN (
    MACN VARCHAR(15) NOT NULL,
    HOCN NVARCHAR(40),
    TENCN NVARCHAR(30) NOT NULL,
    GIOITINH NVARCHAR(5) CHECK (GIOITINH IN ('Nam', 'Nữ')),
    NAMSINH INT CHECK (NAMSINH <= YEAR(GETDATE()) - 18),
    QUEQUAN NVARCHAR(50),
    MAPX VARCHAR(10),
    NGAYNV DATE,
    LCB INT CHECK (LCB >= 0),
    SOCMND VARCHAR(20),
    PRIMARY KEY (MACN),
    UNIQUE (SOCMND),
    FOREIGN KEY (MAPX) REFERENCES PHANXUONG(MAPX)
);
GO
CREATE TABLE SANXUAT (
    NGAYSX DATE NOT NULL,
    MACN VARCHAR(15) NOT NULL,
    MASP VARCHAR(10) NOT NULL,
    SOLUONG INT CHECK (SOLUONG > 0),
    PRIMARY KEY (NGAYSX, MACN, MASP),
    FOREIGN KEY (MACN) REFERENCES CONGNHAN(MACN),
    FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP)
);
GO
CREATE TABLE VANG (
    NGAY DATE NOT NULL,
    MACN VARCHAR(15) NOT NULL,
    LOAIVANG VARCHAR(2) NOT NULL CHECK (LOAIVANG IN ('CP', 'KP')),
    PRIMARY KEY (NGAY, MACN),
    FOREIGN KEY (MACN) REFERENCES CONGNHAN(MACN)
);
GO
